#!/usr/bin/env python3
"""The browser-PC measurement's own programs (Codex R181 VP181-01) — synthetic
moves, no operator data, inside the XYZAC sim's travel (X ±250, Y ±200,
Z −400..0, A ±110; G54 Z −398, T1 100 mm, T7 66 mm, the tool setter at
X150 Y0 Z−300).

  bpc_parse.ngc  PARSE LOAD for the supersede phase: a raster of short
                 collinear G1 steps at Z+5 above the part — many lines for
                 the interpreter (a parse of several seconds), few points
                 after decimation and no contact for the sweep. Under G55
                 (Z −500) it lies below the Z travel: that parse reports
                 limit records; only G54's is the one that stays.
  bpc_run.ngc    RUN LOAD: T1 M600, a short path, T7 M600, then a long feed
                 path at Z−2 while C turns — two mid-run tool-table
                 re-parses: the second runs while the first one's run check
                 still computes (Codex R185: two heartbeats inside the
                 second parse, a slice of that check between them). A
                 PREVIEW-ONLY loop (`#<_task> EQ 0`: the machine skips it)
                 makes every parse of it last a few seconds. (MSG, BPC: …)
                 lines tell the operator in the WebUI when to press keys.

  gen_programs.py [--parse-lines N] [--run-a N] [--run-b N] [--step MM]
                  [--feed F] [--ballast N]
"""
import argparse
import os

NC = os.path.expanduser("~/linuxcnc/nc_files")

HEAD = """%
({title})
(synthetic browser-PC measurement program, generated by gen_programs.py)
G21 G90 G94 G17 G40 G49 G80 G64 P0.05
G54
"""


def parse_program(lines: int) -> str:
    out = [HEAD.format(title="bpc_parse: parse load, raster at Z+5, no contact"),
           "G0 X40 Y40 Z20\n", "G0 Z5\n", "F2000\n"]
    n, step, y, x, d = 0, 0.25, 40.0, 40.0, 1
    while n < lines:
        x += d * step
        if x > 120.0 or x < 40.0:
            d = -d
            x += 2 * d * step
            y += 0.5
            if y > 120.0:
                y = 40.0
        out.append(f"G1 X{x:.3f} Y{y:.3f}\n")
        n += 1
    out.append("G0 Z20\nM2\n%\n")
    return "".join(out)


def run_part(n: int, step: float, c0: float, x0: float, y0: float, x1: float, y1: float):
    """A zigzag of n feed steps of `step` mm in X between x0 and x1, lines
    0.5 mm apart in Y, C turning 0.02° a step (the platter turns under the
    cut — a rotary lever for every pair on the table side)."""
    out, x, y, c, d = [], x0, y0, c0, 1
    for _ in range(n):
        x += d * step
        if x > x1 or x < x0:
            d = -d
            x += 2 * d * step
            y += 0.5
            if y > y1:
                y = y0
        c += 0.02
        out.append(f"G1 X{x:.3f} Y{y:.3f} C{c:.3f}\n")
    return out, c


BALLAST = """(preview only: the interpreter counts, the machine skips it)
#<_bpc_n> = 0
o901 if [#<_task> EQ 0]
o900 repeat [{n}]
#<_bpc_n> = [#<_bpc_n> + 1]
o900 endrepeat
o901 endif
"""


def run_program(a: int, b: int, step: float, feed: float, ballast: int, hold: int) -> str:
    out = [HEAD.format(title="bpc_run: T1 M600, short path, T7 M600, long path while C turns"),
           BALLAST.format(n=ballast) if ballast else "",
           "G53 G0 Z0\n", "T1 M600\n", "G43 H1\n", "S3000 M3\n",
           "(MSG, BPC: jetzt die Pfeiltaste nach unten gedrueckt halten)\n",
           "G0 X60 Y60 C0\n", "G0 Z2\n", "G1 Z-2 F300\n", f"F{feed:g}\n"]
    part, c = run_part(a, step, 0.0, 60.0, 60.0, 110.0, 110.0)
    out += part
    out += ["G0 Z2\n", "G53 G0 Z0\n",
            "T7 M600\n", "G43 H7\n", "G0 X62 Y62\n", "G0 Z2\n", "G1 Z-2 F300\n", f"F{feed:g}\n"]
    part, c = run_part(b, step, c, 62.0, 62.0, 108.0, 108.0)
    out += part[:hold] + ["(MSG, BPC: Taste loslassen)\n"] + part[hold:]
    out += ["G0 Z2\n", "G53 G0 Z0\n", "M5\n", "M2\n", "%\n"]
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--parse-lines", type=int, default=600_000)
    # calibrated on the sim 2026-10-23 (calib-run-*.json): the sim runs these
    # steps at ~22 a second whatever the feed, a run check of 12000 0.5 mm
    # steps took 23 s a sweep on the Mac — 1 mm steps double its path at the
    # same run time; A short, so T7's parse follows T1's check closely
    ap.add_argument("--run-a", type=int, default=10)
    ap.add_argument("--run-b", type=int, default=12000)
    ap.add_argument("--step", type=float, default=1.0)
    ap.add_argument("--feed", type=float, default=3000)
    ap.add_argument("--ballast", type=int, default=3_000_000)
    ap.add_argument("--hold", type=int, default=300, help="part-B steps before the key is released")
    ap.add_argument("--out", default=NC)
    a = ap.parse_args()
    for name, text in (("bpc_parse.ngc", parse_program(a.parse_lines)),
                       ("bpc_run.ngc", run_program(a.run_a, a.run_b, a.step, a.feed, a.ballast, a.hold))):
        p = os.path.join(a.out, name)
        with open(p, "w") as f:
            f.write(text)
        print(name, f"{len(text) / 1e6:.2f} MB", text.count("\n"), "lines")


if __name__ == "__main__":
    main()
