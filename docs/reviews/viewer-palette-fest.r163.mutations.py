 ("h_walk_unclamped", CU, "      x.fLo[fn] = WALK_SPAN.a; x.fHi[fn] = WALK_SPAN.b;", "      x.fLo[fn] = p - Math.min(r0, d); x.fHi[fn] = p + Math.min(r0, d);", "ts", T_U + "::decimal point|next confirmed point above"),
