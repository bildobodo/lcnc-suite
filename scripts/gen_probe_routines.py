#!/usr/bin/env python3
"""What the bundled probe routines do to the probing parameters (P5-2 b, plan
v6, Codex R441/R442): per `subroutines/probe_basic/probe_*.ngc` and
`subroutines/surfacemap/surface_scan.ngc` its content (sha256), the PROBE_KEYS
its own lines assign, the files its o-calls run and whether it reads #3032 —
read with the gateway's own reader (gateway_util.RemapEnv), no configured
remap. The gateway takes a routine's effect as PROVEN only where the file the
interpreter resolves — and each file it calls — has exactly this content
(gateway._routine_effect).

    python3 -I scripts/gen_probe_routines.py            # the table, or why not
    python3 -I scripts/gen_probe_routines.py --write    # lcnc-gateway/probe_routines.py

Guard: lcnc-gateway/test_probe_book.py regenerates it — a new or changed
assignment to #3014–#3059 in a bundled routine fails until the table follows.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "lcnc-gateway"))

from gateway_util import RemapEnv, nc_norm  # noqa: E402
from probe_book import OFFSET_KEY, PROBE_KEYS  # noqa: E402

OUT = ROOT / "lcnc-gateway/probe_routines.py"


def sources() -> list[Path]:
    return sorted((ROOT / "subroutines/probe_basic").glob("probe_*.ngc")) + [
        ROOT / "subroutines/surfacemap/surface_scan.ngc"]


def rows() -> dict[str, tuple[str, tuple[int, ...], tuple[str, ...], bool]]:
    env = RemapEnv([], [], keys=PROBE_KEYS)
    out = {}
    for p in sources():
        raw = p.read_bytes()
        text = raw.decode("utf-8")
        own = env._own_text(text)
        if own is None:
            raise SystemExit(f"{p.name}: a line the reader cannot settle")
        writes, keys, calls, _marks = own
        if keys:
            raise SystemExit(f"{p.name}: a remapped code")
        reads = any(f"#{OFFSET_KEY}" in nc_norm(line) for line in text.splitlines())
        out[p.stem] = (hashlib.sha256(raw).hexdigest(), tuple(sorted(writes)), tuple(sorted(calls)), reads)
    return out


def render() -> str:
    lines = ['"""GENERATED by scripts/gen_probe_routines.py — do not edit.',
             "",
             "The bundled probe routines: name → (sha256 of the file, the probing",
             "parameters its own lines assign, the files its o-calls run, reads #3032).",
             '"""',
             "from typing import Dict, Tuple",
             "",
             "ROUTINES: Dict[str, Tuple[str, Tuple[int, ...], Tuple[str, ...], bool]] = {"]
    for name, (sha, writes, calls, reads) in rows().items():
        lines.append(f'    "{name}": (')
        lines.append(f'        "{sha}",')
        lines.append(f"        {writes!r}, {calls!r}, {reads!r}),".replace("'", '"'))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--write" in sys.argv[1:]:
        OUT.write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
