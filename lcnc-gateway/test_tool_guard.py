class TestLinuxCNCsOwnIndices(unittest.TestCase):

    def test_every_case_as_linuxcnc_reads_it(self):
        self.assertGreaterEqual(len(CASES), 38)
        for what, (data, rows) in CASES.items():
            with self.subTest(what):
                self.assertEqual(tool_table.home_tools(data), {i: (t, p) for i, t, p, _q in rows})

    def test_the_fuzzed_files(self):
        self.assertEqual(len(FUZZ), 40)
        for data, rows in FUZZ:
            with self.subTest(data=data):
                self.assertEqual(tool_table.home_tools(data), {i: (t, p) for i, t, p, _q in rows})

    def test_the_1001st_p_word_takes_no_index(self):
        # (the compiled reader: 1000 home entries, "Out-of-range nonrandom_idx")
        data = b"".join(b"T%d P%d Z1\n" % (n, n) for n in range(1, 1003))
        got = tool_table.home_tools(data)
        self.assertEqual((len(got), got[1000], 1001 in got), (1000, (1000, 1000), False))

    def test_what_is_not_mirrored_is_named_never_guessed(self):
        for line in (b"T5 P5 Z0x1f\n", b"T5 P5 Zinf\n", b"T5 P5 D-NAN\n", b"T5 P5 Z1 ; a\0b\n"):
            with self.subTest(line=line):
                with self.assertRaises(tool_table.ToolTableUnreadable) as e:
                    tool_table.home_tools(b"T1 P1 Z1\n" + line)
                self.assertEqual(str(e.exception), "Line 2 not readable — fix it in an editor")

    def test_the_line_number_is_the_files_not_the_pieces(self):
        data = b";" + b"-" * 600 + b"\nT5 P5 Zinf\n"
        with self.assertRaises(tool_table.ToolTableUnreadable) as e:
            tool_table.home_tools(data)
        self.assertIn("Line 2 ", str(e.exception))


# ---- what the writer emits -------------------------------------------------------

def row(tool=5, **fields):
    return {"T": tool, "P": tool, "Z": 50.0, "D": 5.0, "remark": "", **fields}


class TestTheWritersLine(unittest.TestCase):

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.path = os.path.join(tmp.name, "tool.tbl")
        with open(self.path, "w") as f:
            f.write("before\n")

    def refused(self, why, *rows):
        with self.assertRaises(ValueError) as e:
            write_tool_table(self.path, list(rows))
        self.assertEqual(str(e.exception), why)
        with open(self.path) as f:
            self.assertEqual(f.read(), "before\n", "nothing written")

    def test_255_bytes_with_the_newline_is_one_line_one_more_is_not(self):
        bare = len(write_tool_table(self.path, [row(remark="r")]).split(b"\n")[1]) + 1 - 1   # a line without its remark
        fits = "r" * (255 - bare)
        data = write_tool_table(self.path, [row(remark=fits)])
        self.assertEqual(max(len(ln) + 1 for ln in data.split(b"\n")), 255)
        self.assertEqual(tool_table.home_tools(data), {1: (5, 5)})
        with open(self.path, "w") as f:
            f.write("before\n")
        self.refused("T5: line too long for LinuxCNC — shorten its description", row(remark=fits + "r"))
        # characters are not bytes
        self.refused("T5: line too long for LinuxCNC — shorten its description", row(remark=fits[:-1] + "ä"))

    def test_the_ghost_the_writer_made(self):
        data, rows = CASES["ghost of the writer"]
        self.assertIn((2, 9, 9, 0), rows, "LinuxCNC holds a T9 no one wrote")
        remark = data.split(b"; ", 1)[1].split(b"\n")[0].decode()
        self.assertLessEqual(len(remark), 255, "a text the command admits")
        self.refused("T1: line too long for LinuxCNC — shorten its description",
                     row(1, Z=10.0, D=6.0, remark=remark), row(2, Z=20.0, D=2.0, remark="two"))

    def test_the_numbers_of_every_field_count(self):
        self.refused("T5: line too long for LinuxCNC — check its numbers", row(Z=1e300))
        self.refused("T5: line too long for LinuxCNC — check its numbers",
                     row(**{k: -math.pi * 10 ** 24 for k in "XYZABCUVWDIJ"}))

    def test_a_line_break_a_nul_no_text(self):
        for c in "\n\r\0":
            self.refused("T5: line break or NUL in its description — remove it", row(remark=f"a{c}b"))
        self.refused("T5: description is not valid text — retype it", row(remark="a\udc80"))

    def test_the_integers(self):
        for k, name in (("P", "P"), ("Q", "Q")):
            for v in (2 ** 31, -2 ** 31 - 1, 2 ** 32 + 3):
                self.refused(f"T5: {name} is past LinuxCNC's integers — correct it", row(**{k: v}))
            for v in (2 ** 31 - 1, -2 ** 31):
                self.assertTrue(write_tool_table(self.path, [row(**{k: v})]))
                with open(self.path, "w") as f:
                    f.write("before\n")
        self.refused("T2147483648 is past LinuxCNC's integers — renumber it", row(2 ** 31))
        self.refused("A tool number is past LinuxCNC's integers — renumber it", row(10 ** 30))

    def test_a_number_that_is_none(self):
        for k in "XYZABCUVWDIJ":
            for v in (math.inf, -math.inf, math.nan):
                self.refused(f"T5: {k} is not a finite number — correct it", row(**{k: v}))

    def test_a_whole_number_that_is_none(self):
        # int(inf) is an OverflowError, int(nan) a bare ValueError: neither names the tool
        for k in "PQ":
            for v in (math.inf, -math.inf, math.nan):
                with self.assertRaises(tool_table.ToolTableUnwritable):
                    tool_table.tool_table_bytes([row(**{k: v})])
                self.refused(f"T5: {k} is not a finite number — correct it", row(**{k: v}))

    def test_no_foreign_file_makes_one(self):
        # the parser reads whole numbers only; one with more digits than Python converts is an
        # UNREAD line, named — never an exception of the read
        for word in ("Qinf", "Q-inf", "Qnan", "Q1e999", "Pinf", "P1e999", "Tinf"):
            unread = []
            self.assertEqual(parse_tool_table_bytes(f"T5 P5 {word}\n".encode() if word[0] == "Q" else f"{word} Z1\n".encode(),
                                                    unread=unread), [], word)
            self.assertEqual([u["line"] for u in unread], [1], word)
        for data in (b"T5 P5 Q" + b"9" * 5000 + b"\n", b"T5 P" + b"9" * 5000 + b"\n", b"T" + b"9" * 5000 + b" P5\n"):
            unread = []
            self.assertEqual(parse_tool_table_bytes(b"T1 P1 Z1\n" + data, unread=unread)[0]["T"], 1)
            self.assertEqual([u["line"] for u in unread], [2])
            with self.assertRaises(tool_table.ToolTableUnreadable):
                parse_tool_table_bytes(data, strict=True)

    def test_one_bad_row_writes_no_row(self):
        self.refused("T8: line too long for LinuxCNC — shorten its description",
                     row(2), row(5), row(8, remark="x" * 240))

    def test_what_is_written_linuxcnc_reads_row_by_row(self):
        rows = [row(t, P=t + 100, remark=r, Q=q) for t, r, q in
                ((9, "", 0), (2, "ä" * 90, 3), (5, "a ; b # T7 P7", -1), (7, "\ttab", 2 ** 31 - 1))]
        data = write_tool_table(self.path, rows)
        self.assertEqual(tool_table.home_tools(data), {1: (2, 102), 2: (5, 105), 3: (7, 107), 4: (9, 109)})
        self.assertEqual([r["T"] for r in parse_tool_table_bytes(data, strict=True)], [2, 5, 7, 9])

    def test_no_description_is_no_error(self):
        for text in (None, ""):
            self.assertNotIn(b" ; ", write_tool_table(self.path, [row(remark=text)]))

    def test_the_reasons_are_short(self):
        for tool in (1, TOOL_NUMBER_MAX):
            for bad in (dict(remark="x" * 255), dict(Z=1e300), dict(remark="\n"), dict(remark="\ud800"),
                        dict(P=2 ** 40), dict(Z=math.inf)):
                with self.assertRaises(ValueError) as e:
                    tool_table.tool_table_bytes([row(tool, **bad)])
                self.assertLessEqual(len(str(e.exception)), REASON_MAX_CHARS, str(e.exception))


