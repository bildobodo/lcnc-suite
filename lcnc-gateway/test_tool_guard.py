class TestTheReadersPins(_HelperHarness):
    """hal_reader.py as a real subprocess under the stub hal."""
    script = "hal_reader.py"
    sock_env = "WEBUI_READER_SOCK"

    def setUp(self):
        fd, self.values = tempfile.mkstemp(suffix=".json")
        os.close(fd)
        self.addCleanup(os.unlink, self.values)
        self.give({"iocontrol.0.tool-prep-number": 5, "iocontrol.0.tool-prep-pocket": 15,
                   "iocontrol.0.tool-prepare": True})
        os.environ["FAKE_HAL_VALUES"] = self.values
        self.addCleanup(os.environ.pop, "FAKE_HAL_VALUES", None)
        super().setUp()

    def give(self, values):
        with open(self.values, "w") as f:
            json.dump(values, f)

    def snapshots(self, steps):
        """The first snapshot `done` accepts, for each (change, done)."""
        async def run():
            b, out = self._bridge(self.instance), []
            task = asyncio.create_task(b.reader_recv_loop())
            try:
                for change, done in steps:
                    change()
                    end = time.monotonic() + 5.0
                    while time.monotonic() < end:
                        st = b.reader_state()
                        if st is not None and done(st[0]):
                            out.append(st[0])
                            break
                        await asyncio.sleep(0.01)
            finally:
                task.cancel()
                try:
                    await task
                except asyncio.CancelledError:
                    pass
            return out
        return asyncio.run(run())

    def test_the_preparation_on_the_snapshot_and_absent_when_unread(self):
        got = self.snapshots([
            (lambda: None, lambda s: "tool_prep_pocket" in s),
            (lambda: self.give({"iocontrol.0.tool-prep-number": 5}), lambda s: "tool_prep_pocket" not in s),
        ])
        self.assertEqual(len(got), 2)
        self.assertEqual([got[0].get(k) for k in ("tool_prep_number", "tool_prep_pocket", "tool_prepare")],
                         [5, 15, True])
        self.assertIs(type(got[0]["tool_prep_pocket"]), int)
        self.assertEqual(got[1].get("tool_prep_number"), 5)
        for k in ("tool_prep_pocket", "tool_prepare"):
            self.assertNotIn(k, got[1], "a pin that did not read is absent, never 0 / FALSE")


