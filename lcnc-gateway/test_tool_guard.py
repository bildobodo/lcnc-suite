FILE = b"T2 P2 Z20\nT5 P5 Z50\nT8 P8 Z80\n"


class TestPreparedRefusal(unittest.TestCase):

    def ask(self, data=FILE, scope=None, index=2, preparing=False, number=5, pocket=5):
        return tool_proof.prepared_refusal(data, scope, index, preparing, number, pocket)

    def test_the_same_index_tool_and_pocket(self):
        self.assertIsNone(self.ask())
        self.assertIsNone(self.ask(data=b"T2 P9 Z0\nT5 P5 Z1 D9 ; other\n"))

    def test_another_row_pocket_or_none_at_the_index(self):
        why = "A tool is prepared — change to another tool or send T0"
        for data in (b"T2 P2\nT5 P9\n", b"T5 P5\nT2 P2\n", b"T2 P2\n", b"", b"T2 P2\nT8 P8\nT5 P5\n"):
            with self.subTest(data=data):
                self.assertEqual(self.ask(data=data), why)

    def test_linuxcncs_index_not_the_rows_position(self):
        commented = b"T2 P2 Z20\n#T3 P3 Z30\nT5 P5 Z50\n"
        self.assertIsNone(self.ask(data=commented, index=3))
        self.assertIsNotNone(self.ask(data=commented, index=2))
        semicolon = b"T2 P2 Z20\n;T3 P3 Z30\nT5 P5 Z50\n"
        self.assertIsNone(self.ask(data=semicolon, index=2))

    def test_the_pins_decide_never_the_file(self):
        self.assertIsNotNone(self.ask(data=b"T2 P2\nT5 P9\n", pocket=5))
        self.assertIsNone(self.ask(data=b"T2 P2\nT5 P9\n", pocket=9))
        self.assertIsNotNone(self.ask(number=6))

    def test_nothing_prepared(self):
        for index in (-1, 0):
            for number, pocket in ((0, 0), (6, 6), (None, None)):
                self.assertIsNone(self.ask(data=b"", index=index, number=number, pocket=pocket))
            # an older reader: no tool-prepare pin — number 0 proves it, else unknown
            self.assertIsNone(self.ask(data=b"", index=index, preparing=None, number=0, pocket=None))
            for number in (6, None):
                self.assertEqual(self.ask(index=index, preparing=None, number=number, pocket=None),
                                 tool_proof.PREPARED_UNKNOWN)

    def test_unknown_is_never_a_default(self):
        for index in (None, "2", 2.0, True, False, -2):
            self.assertEqual(self.ask(index=index), tool_proof.PREPARED_UNREAD, index)
        for number, pocket in ((None, 5), (5, None), (5.0, 5), (5, "5"), (True, 5)):
            self.assertEqual(self.ask(number=number, pocket=pocket), tool_proof.PREPARED_UNKNOWN)
        self.assertEqual(self.ask(number=0, pocket=0), tool_proof.PREPARED_CLEARED)
        self.assertEqual(self.ask(data=b"T2 P2\nT5 P5 Zinf\n"), "Line 2 not readable — fix it in an editor")

    def test_a_preparation_not_known_to_have_ended(self):
        # MT-I44: a new T keeps the old index until its tool-prepared comes
        for preparing in (None, 0, "FALSE"):
            self.assertEqual(self.ask(preparing=preparing), tool_proof.PREPARED_UNKNOWN, preparing)
        self.assertIsNone(self.ask(preparing=False))

    def test_under_way(self):
        for index in (-1, 0, 2):
            self.assertEqual(self.ask(index=index, preparing=True), tool_proof.PREPARING)

    def test_no_index_is_judged_outside_rule_rs_scope(self):
        for scope in (tool_proof.SCOPE_RANDOM, tool_proof.SCOPE_DATABASE, tool_proof.SCOPE_UNKNOWN):
            self.assertEqual(self.ask(scope=scope), f"Prepared tool not checked ({scope}) — send T0")
            self.assertIsNone(self.ask(scope=scope, index=-1, number=0, pocket=0))

    def test_the_reasons_are_short(self):
        for why in (self.ask(data=b"", number=TOOL_NUMBER_MAX), tool_proof.PREPARED_UNREAD, tool_proof.PREPARED_UNKNOWN,
                    tool_proof.PREPARING, tool_proof.PREPARED_CLEARED,
                    *(self.ask(scope=s) for s in (tool_proof.SCOPE_RANDOM, tool_proof.SCOPE_DATABASE,
                                                  tool_proof.SCOPE_UNKNOWN))):
            self.assertLessEqual(len(why), REASON_MAX_CHARS, why)


