class CommandLike(Protocol):
    """`linuxcnc.command` as the code calls it. Every method positional-only
    (PyArg_ParseTuple), every one None except wait_complete; `serial` is the
    serial number of the last command sent."""
    @property
    def serial(self) -> int: ...
    def abort(self) -> None: ...
    @overload
    def auto(self, fn: int, /) -> None: ...            # AUTO_PAUSE / RESUME / STEP ("i")
    @overload
    def auto(self, fn: int, line: int, /) -> None: ...  # AUTO_RUN from a line ("ii")
    def feedrate(self, scale: float, /) -> None: ...
    def flood(self, on: int, /) -> None: ...
    def home(self, joint: int, /) -> None: ...
    @overload
    def jog(self, fn: int, jjogmode: int, ja_value: int, /) -> None: ...                    # JOG_STOP
    @overload
    def jog(self, fn: int, jjogmode: int, ja_value: int, vel: float, /) -> None: ...        # JOG_CONTINUOUS
    @overload
    def jog(self, fn: int, jjogmode: int, ja_value: int, vel: float, inc: float, /) -> None: ...  # JOG_INCREMENT
    def load_tool_table(self) -> None: ...
    def maxvel(self, velocity: float, /) -> None: ...
    def mdi(self, command: str, /) -> None: ...
    def mist(self, on: int, /) -> None: ...
    def mode(self, mode: int, /) -> None: ...
    def program_open(self, path: str, /) -> None: ...
    def rapidrate(self, scale: float, /) -> None: ...
    def reset_interpreter(self) -> None: ...
    def set_block_delete(self, on: int, /) -> None: ...
    def set_optional_stop(self, on: int, /) -> None: ...
    @overload
    def spindle(self, direction: int, /) -> None: ...                                   # SPINDLE_OFF
    @overload
    def spindle(self, direction: int, spindle: float, /) -> None: ...                   # INCREASE / DECREASE / CONSTANT / OFF
    @overload
    def spindle(self, direction: int, speed: float, spindle: float, /) -> None: ...     # FORWARD / REVERSE
    @overload
    def spindle(self, direction: int, speed: float, spindle: float, wait: int, /) -> None: ...
    def spindleoverride(self, scale: float, spindle: int = 0, /) -> None: ...
    def state(self, state: int, /) -> None: ...
    def task_plan_synch(self) -> None: ...
    def teleop_enable(self, enable: int, /) -> None: ...
    def unhome(self, joint: int, /) -> None: ...
    def wait_complete(self, timeout: float = 5.0, /) -> int: ...


class ErrorChannelLike(Protocol):
    def poll(self) -> tuple[int, str] | None: ...


class IniLike(Protocol):
    def find(self, section: str, option: str, num: int = 1, /) -> str | None: ...
    def findall(self, section: str, option: str, /) -> list[str]: ...


STAT_FIELDS: tuple[str, ...] = tuple(
    n for n in vars(StatLike) if not n.startswith("_") and n != "poll")
COMMAND_METHODS: tuple[str, ...] = tuple(
    n for n in vars(CommandLike) if not n.startswith("_"))
#: status names read with a FALLBACK that a version may lack — named, never
#: required of the binding: `spindle_override` (older bindings; 2.9.4 has
#: only the spindle row's `override`, which get_spindle_override falls back
#: to). The one read that had no fallback, `spindle_override_enabled`, was a
#: defect (always its default True) and reads the spindle row now.
OPTIONAL_STAT_FIELDS: frozenset[str] = frozenset({"spindle_override"})
