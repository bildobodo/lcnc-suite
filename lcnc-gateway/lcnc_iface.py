"""The LinuxCNC binding surface the product code uses — ONE interface that the
real binding's stub (typings/linuxcnc.pyi) and the tests' fake
(fake_linuxcnc.py) are each checked against (package 2, Codex R352/R353
VM352-01).

Shapes and return types mirror the 2.9.4 binding's source (emcmodule.cc),
never the docs: positional-only parameters (PyArg_ParseTuple, no keywords),
`wait_complete` an int (RCS_DONE / RCS_ERROR / -1), every other command
None. The value types of the joint / spindle dicts and the tool table rows
were read from a real 2.9.4 status. Protocols, not classes to inherit: a
conforming object needs only these members with these types.

`STAT_FIELDS` are the GUARANTEED status fields — the stat members below.
Every literal name the code reads through `safe_get` must be one of them or
one of `OPTIONAL_STAT_FIELDS` (named, read with a fallback, not required of
every version); test_lcnc_iface.py holds the code to that, and the native
name check holds the real binding to `STAT_FIELDS` / `COMMAND_METHODS`.
"""
from __future__ import annotations

from typing import Protocol, TypedDict, overload


class JointStatus(TypedDict):
    """One row of `stat.joint` (emcmodule.cc Stat_joint; types read live)."""
    jointType: int
    units: float
    backlash: float
    min_position_limit: float
    max_position_limit: float
    max_ferror: float
    min_ferror: float
    ferror_current: float
    ferror_highmark: float
    output: float
    input: float
    velocity: float
    inpos: int
    homing: int
    homed: int
    fault: int
    enabled: int
    min_soft_limit: int
    max_soft_limit: int
    min_hard_limit: int
    max_hard_limit: int
    override_limits: int


class SpindleStatus(TypedDict):
    """One row of `stat.spindle` (emcmodule.cc Stat_spindle). Its
    `override_enabled` is the ONLY spindle-override switch — there is no
    `stat.spindle_override_enabled` in 2.9.4."""
    brake: int
    direction: int
    enabled: int
    override_enabled: bool
    speed: float
    override: float
    homed: bool
    orient_state: int
    orient_fault: int


